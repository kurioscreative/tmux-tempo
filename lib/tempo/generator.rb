# frozen_string_literal: true

require "fileutils"

module Tempo
  # Static generation (D2): Ruby writes a pure-sh loader containing the
  # fully resolved plugin list plus a freshness fingerprint; tmux server
  # start executes the artifact and never touches Ruby. Generation only
  # ever scans local files — never the network.
  class Generator
    # The runner preserves the contract's execution model: top-level *.tmux
    # files only, byte-wise sorted (licensed drop of locale glob order),
    # run as executables, output discarded, failures isolated. The
    # non-executable warning is intentional divergence 4.
    ARTIFACT_HEADER = <<~'SH'
      #!/bin/sh
      # Generated by tempo. Do not edit — regenerated when tmux config changes.
      run_plugin_dir() {
      	[ -d "$1" ] || return 0
      	for _f in "$1"*.tmux; do
      		[ -e "$_f" ] && printf '%s\n' "$_f"
      	done | LC_ALL=C sort | while IFS= read -r _f; do
      		[ -f "$_f" ] || continue
      		if [ -x "$_f" ]; then
      			"$_f" >/dev/null 2>&1 || :
      		else
      			printf 'tempo: warning: skipping non-executable %s\n' "$_f" >&2
      		fi
      	done
      	return 0
      }
    SH

    def initialize(env)
      @env = env
    end

    def generate
      FileUtils.mkdir_p(@env.data_dir)
      write_atomic(@env.artifact_path, artifact_body)
      File.chmod(0o755, @env.artifact_path)
      # Fingerprint last: a crash mid-generation leaves a stale fingerprint,
      # which just means "regenerate next time".
      write_atomic(@env.fingerprint_path, fingerprint_body)
    end

    def artifact_body
      lines = [ARTIFACT_HEADER]
      @env.specs.each do |spec|
        lines << "run_plugin_dir #{sh_quote("#{File.join(@env.plugin_path, spec.name)}/")}"
      end
      lines << "exit 0"
      "#{lines.join("\n")}\n"
    end

    # Everything the sh hot path re-checks: format version, the resolved
    # plugin path, the live @tpm_plugins value, and mtime+size of every
    # config file consulted (missing files recorded so their creation
    # invalidates too).
    def fingerprint_body
      lines = ["tempo-fingerprint 1"]
      lines << "path #{@env.plugin_path}"
      lines << "tpm_plugins #{@env.tpm_plugins_option}".rstrip
      @env.scan.entries.each do |e|
        lines << (e.exists ? "f #{e.mtime} #{e.size} #{e.path}" : "m #{e.path}")
      end
      "#{lines.join("\n")}\n"
    end

    private

    def sh_quote(str)
      "'#{str.gsub("'", "'\\\\''")}'"
    end

    def write_atomic(path, body)
      tmp = "#{path}.tmp#{Process.pid}"
      File.write(tmp, body)
      File.rename(tmp, path)
    end
  end
end
